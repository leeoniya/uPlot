// Run with Node or Bun: node scripts/patch-echarts-heatmap.mjs [--revert]
import { readFile, writeFile, rename, rm } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export const version = '6.1.0';
export const downloadUrl = `https://fastly.jsdelivr.net/npm/echarts@${version}/dist/echarts.js`;
export const bundlePath = `demos/lib/echarts-${version}.heatmap-patched.js`;
const demoPath = 'demos/heatmap-cells-echarts.html';
const originalCall = 'this._renderOnGridLike(seriesModel, api, 0, seriesModel.getData().count());';
const patchedCall = 'this._renderOnGridLike(seriesModel, api, 0, seriesModel.getData().count(), false);';
const count = (text, match) => text.split(match).length - 1;

export function patchBundle(source) {
	if (count(source, originalCall) != 1 || count(source, patchedCall) != 0)
		throw new Error('Expected exactly one unpatched heatmap render call; the downloaded ECharts source does not match this patch');
	// Omitted useIncremental defaults to true in getIncrementalId(), even in normal render().
	return `// ECharts ${version}: heatmap non-progressive render fix. Generated by scripts/patch-echarts-heatmap.mjs.\n` + source.replace(originalCall, patchedCall);
}

export function rewireDemo(html, revert = false) {
	const changes = [
		[`<script src="https://fastly.jsdelivr.net/npm/echarts@${version}/dist/echarts.min.js"></script>`,
		 `<script src="./lib/echarts-${version}.heatmap-patched.js"></script>`],
		['ECharts loads from a CDN and requires network access.',
		 'ECharts uses a local heatmap patch. Run <code>node scripts/patch-echarts-heatmap.mjs</code> to download and generate the library.'],
		['Serve the repository root over HTTP and allow the ECharts CDN request.',
		 'Serve the repository root over HTTP. If the local library is missing, run node scripts/patch-echarts-heatmap.mjs.'],
	];
	for (const change of changes) {
		const [before, after] = revert ? [change[1], change[0]] : change;
		const oldCount = count(html, before), newCount = count(html, after);
		if (oldCount == 1 && newCount == 0)
			html = html.replace(before, after);
		else if (oldCount != 0 || newCount != 1)
			throw new Error(`Cannot safely update ${demoPath}: expected one occurrence of ${JSON.stringify(before)} or its replacement`);
	}
	return html;
}

async function replaceFile(url, content) {
	const temporary = new URL(`${url.href}.${randomUUID()}.tmp`);
	try {
		await writeFile(temporary, content, { flag: 'wx' });
		await rename(temporary, url);
	}
	finally {
		await rm(temporary, { force: true });
	}
}

export async function patchDemo(root = new URL('../', import.meta.url), fetchBundle = fetch) {
	const controller = new AbortController();
	const timer = setTimeout(() => controller.abort(new Error('ECharts download timed out after 60 seconds')), 60000);
	let source;
	try {
		const response = await fetchBundle(downloadUrl, { signal: controller.signal });
		if (!response.ok)
			throw new Error(`ECharts download failed: HTTP ${response.status}`);
		source = await response.text();
	}
	finally {
		clearTimeout(timer);
	}
	const patched = patchBundle(source);
	const demoUrl = new URL(demoPath, root);
	const originalHtml = await readFile(demoUrl, 'utf8');
	const html = rewireDemo(originalHtml);
	// Validate everything before writing; install the bundle before switching the script URL.
	await replaceFile(new URL(bundlePath, root), patched);
	if (html != originalHtml)
		await replaceFile(demoUrl, html);
	return { bundlePath, demoPath };
}

export async function revertDemo(root = new URL('../', import.meta.url)) {
	const demoUrl = new URL(demoPath, root);
	const originalHtml = await readFile(demoUrl, 'utf8');
	const html = rewireDemo(originalHtml, true);
	if (html != originalHtml)
		await replaceFile(demoUrl, html);
	return { demoPath };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href == import.meta.url) {
	try {
		const args = process.argv.slice(2);
		if (args.length > 1 || (args.length == 1 && args[0] != '--revert' && args[0] != '--help'))
			throw new Error('Usage: node scripts/patch-echarts-heatmap.mjs [--revert | --help]');
		if (args[0] == '--help') {
			console.log('Usage: node scripts/patch-echarts-heatmap.mjs [--revert]\nDefault: download and patch ECharts, then use the local bundle.\n--revert: restore the CDN URL and loading instructions without downloading or deleting files.');
		}
		else if (args[0] == '--revert') {
			const result = await revertDemo();
			console.log(`Restored CDN loading in ${result.demoPath}\nThe local bundle was left in place. The ECharts GL demo is unchanged.`);
		}
		else {
			console.log(`Downloading ${downloadUrl}`);
			const result = await patchDemo();
			console.log(`Patched ${result.bundlePath}\nRewired ${result.demoPath}\nThe ECharts GL demo is unchanged.`);
		}
	}
	catch (error) {
		console.error(error.message);
		process.exitCode = 1;
	}
}
