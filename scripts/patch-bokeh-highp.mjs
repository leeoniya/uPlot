// Run with Node or Bun: node scripts/patch-bokeh-highp.mjs [--original | --revert]
import { readFile, writeFile, rename, rm } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { Script } from 'node:vm';

export const version = '3.10.0';
export const bundles = ['bokeh', 'bokeh-gl', 'bokeh-api'].map(name => ({
	name,
	url: `https://cdn.bokeh.org/bokeh/release/${name}-${version}.js`,
	path: `demos/lib/${name}-${version}.js`,
}));
export const bundlePath = `demos/lib/bokeh-gl-${version}.highp.js`;
export const demoPath = 'demos/heatmap-cells-bokeh.html';
const count = (text, match) => text.split(match).length - 1;

export function patchBundle(source) {
	const seen = new Set();
	// Source-derived diagnostic, not an official fix: screen-space marker arithmetic uses mediump in BokehJS 3.10.0.
	const modules = /(\/\* models\/glyphs\/webgl\/marker\.(vert|frag)\.js \*\/ function _\([^)]*\) \{\s*__esModule\(\);\s*const shader = `\n)([^`]*)(`;)/g;
	const patched = source.replace(modules, (match, prefix, kind, shader, suffix) => {
		if (seen.has(kind) || !shader.startsWith('precision mediump float;') || count(shader, 'precision mediump float;') != 1)
			throw new Error(`Expected one unpatched marker.${kind} shader; the Bokeh source does not match this patch`);
		seen.add(kind);
		return prefix + shader.replace('precision mediump float;', 'precision highp float;') + suffix;
	});
	if (seen.size != 2 || ['vert', 'frag'].some(kind => count(source, `/* models/glyphs/webgl/marker.${kind}.js */`) != 1))
		throw new Error('Expected exactly two unpatched marker shader modules; the Bokeh source does not match this patch');
	return `// BokehJS ${version}: experimental highp marker shaders. Generated by scripts/patch-bokeh-highp.mjs.\n` + patched;
}

export function rewireDemo(html, mode = 'highp') {
	if (!['highp', 'original', 'cdn'].includes(mode))
		throw new Error(`Unknown Bokeh mode: ${mode}`);
	const note = 'This comparison uses the positive log view only. WebGL requires browser support.';
	const instructions = 'Serve the repository root over HTTP and check CDN access.';
	const changes = bundles.map(bundle => ({
		cdn: `<script src="https://cdn.bokeh.org/bokeh/release/${bundle.name}-${version}.min.js"></script>`,
		original: `<script src="./lib/${bundle.name}-${version}.js"></script>`,
		highp: `<script src="./lib/${bundle.name}-${version}${bundle.name == 'bokeh-gl' ? '.highp' : ''}.js"></script>`,
	}));
	changes.push({
		cdn: note,
		original: note + ' Local Bokeh bundles use the original marker shaders (mediump).',
		highp: note + ' Local Bokeh bundles use experimental highp marker shaders; this is a source-derived diagnostic patch, not an official fix.',
	}, {
		cdn: instructions,
		original: 'Serve the repository root over HTTP. If the local libraries are missing, run node scripts/patch-bokeh-highp.mjs --original.',
		highp: 'Serve the repository root over HTTP. If the local libraries are missing, run node scripts/patch-bokeh-highp.mjs.',
	});
	for (const variants of changes) {
		// Longest first: the original note and the highp command are prefixes of other variants.
		const candidates = [...new Set(Object.values(variants))].sort((a, b) => b.length - a.length);
		let remainder = html, found;
		for (const candidate of candidates) {
			const n = count(remainder, candidate);
			if (n == 0) continue;
			if (n != 1 || found != null)
				throw new Error(`Cannot safely update ${demoPath}: ambiguous Bokeh scripts or loading instructions`);
			found = candidate;
			remainder = remainder.replace(candidate, '');
		}
		if (found == null)
			throw new Error(`Cannot safely update ${demoPath}: missing Bokeh scripts or loading instructions`);
		html = html.replace(found, variants[mode]);
	}
	return html;
}

async function replaceFile(url, content) {
	const temporary = new URL(`${url.href}.${randomUUID()}.tmp`);
	try {
		await writeFile(temporary, content, { flag: 'wx' });
		await rename(temporary, url);
	}
	finally {
		await rm(temporary, { force: true });
	}
}

export async function patchDemo(root = new URL('../', import.meta.url), fetchBundle = fetch, mode = 'highp') {
	if (mode != 'highp' && mode != 'original')
		throw new Error(`Unknown Bokeh download mode: ${mode}`);
	const demoUrl = new URL(demoPath, root);
	const originalHtml = await readFile(demoUrl, 'utf8');
	const html = rewireDemo(originalHtml, mode);
	const downloads = [];
	for (const bundle of bundles) {
		const controller = new AbortController();
		const timer = setTimeout(() => controller.abort(new Error('Bokeh download timed out after 60 seconds')), 60000);
		try {
			const response = await fetchBundle(bundle.url, { signal: controller.signal });
			if (!response.ok)
				throw new Error(`Bokeh download failed for ${bundle.name}: HTTP ${response.status}`);
			const source = await response.text();
			new Script(source, { filename: bundle.path });
			downloads.push({ path: bundle.path, source });
		}
		finally {
			clearTimeout(timer);
		}
	}
	const patched = patchBundle(downloads[1].source);
	new Script(patched, { filename: bundlePath });
	// Validate all downloads before writing; install the bundles before switching the demo URLs.
	for (const { path, source } of [...downloads, { path: bundlePath, source: patched }])
		await replaceFile(new URL(path, root), source);
	if (html != originalHtml)
		await replaceFile(demoUrl, html);
	return { bundlePath, demoPath };
}

export async function revertDemo(root = new URL('../', import.meta.url)) {
	const demoUrl = new URL(demoPath, root);
	const originalHtml = await readFile(demoUrl, 'utf8');
	const html = rewireDemo(originalHtml, 'cdn');
	if (html != originalHtml)
		await replaceFile(demoUrl, html);
	return { demoPath };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href == import.meta.url) {
	try {
		const args = process.argv.slice(2);
		const usage = 'Usage: node scripts/patch-bokeh-highp.mjs [--original | --revert | --help]';
		if (args.length > 1 || (args.length == 1 && !['--original', '--revert', '--help'].includes(args[0])))
			throw new Error(usage);
		if (args[0] == '--help') {
			console.log(usage + '\nDefault: download Bokeh 3.10.0 and enable experimental highp marker shaders.\n--original: download the same bundles and use the original local mediump shaders.\n--revert: restore CDN loading without downloading or deleting files.\nOnly marker shader precision changes; this is a diagnostic experiment, not a confirmed fix.');
		}
		else if (args[0] == '--revert') {
			await revertDemo();
			console.log(`Restored CDN loading in ${demoPath}\nLocal bundles were left in place.`);
		}
		else {
			const mode = args[0] == '--original' ? 'original' : 'highp';
			console.log(`Downloading Bokeh ${version} from https://cdn.bokeh.org (${mode} marker shaders)`);
			await patchDemo(undefined, undefined, mode);
			console.log(`Rewired ${demoPath} to local bundles (${mode}). Reload the demo to compare.\nGenerated ${bundlePath}; original bundles were retained for comparison.`);
		}
	}
	catch (error) {
		console.error(error.message);
		process.exitCode = 1;
	}
}
